const { chromium } = require('playwright');
const path = require('path');
const R = process.argv[2] || path.resolve(__dirname, '..');
const url = 'file://' + path.resolve(R, 'index.html');
const out = n => path.resolve(R, 'docs/screenshots', n);
(async () => {
  const browser = await chromium.launch();
  const mk = async (opts = {}) => {
    const ctx = await browser.newContext({ viewport:{ width:1440, height:1000 }, deviceScaleFactor:1.5, ...opts });
    await ctx.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
    const p = await ctx.newPage();
    p.on('pageerror', e => console.log('PAGEERROR', e.message));
    p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
    await p.goto(url); await p.waitForTimeout(400);
    return { ctx, p };
  };
  const sig = (p, ...s) => p.evaluate(list => { for (const x of list) doSignal(x); }, s);
  let { ctx, p } = await mk();
  await p.screenshot({ path: out('01-simulator-start.png'), fullPage:true });
  await sig(p, 'click', 'lp_none');
  await p.screenshot({ path: out('02-landing-page-miss.png'), fullPage:true });
  await sig(p, 'click', 'start', 'abandon');
  await p.screenshot({ path: out('03-abandonment-branch.png'), fullPage:true });
  await sig(p, 'noresp', 'click', 'submit');
  await p.screenshot({ path: out('04-engaged-complete.png'), fullPage:true });
  await p.evaluate(() => startJourney());
  await sig(p, 'ignore', 'noresp', 'ignore');
  await p.screenshot({ path: out('05-silent-path-paused.png'), fullPage:true });
  await p.evaluate(() => startJourney());
  await p.click('[data-sig="notnow"]'); await p.waitForTimeout(150);
  await p.screenshot({ path: out('06-not-now-reasons.png'), fullPage:true });
  await p.evaluate(() => { personaId = 'harbor'; renderPersonas(); startJourney(); doSignal('click'); doSignal('lp_none'); doSignal('risk'); });
  await p.screenshot({ path: out('07-risk-suppressed.png'), fullPage:true });
  await p.click('#tab-exp'); await p.waitForTimeout(150);
  await p.screenshot({ path: out('08-experiments.png'), fullPage:true });
  await p.click('#tab-comp'); await p.waitForTimeout(150);
  await p.screenshot({ path: out('09-compliance-check.png'), fullPage:true });
  await p.click('#tab-how'); await p.waitForTimeout(150);
  await p.screenshot({ path: out('10-how-it-works.png'), fullPage:true });
  await p.evaluate(() => { try { localStorage.clear(); } catch(e){} });
  await ctx.close();
  ({ ctx, p } = await mk({ colorScheme:'dark' }));
  await p.click('#tab-sim'); await sig(p, 'click', 'lp_none');
  await p.screenshot({ path: out('11-dark-mode.png'), fullPage:true });
  await ctx.close();
  ({ ctx, p } = await mk({ viewport:{ width:390, height:844 }, deviceScaleFactor:2 }));
  await p.click('#tab-sim');
  await p.screenshot({ path: out('12-mobile.png'), fullPage:false });
  const ov = await p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
  console.log('mobile horizontal overflow px:', ov);
  await ctx.close();
  await browser.close();
})();
